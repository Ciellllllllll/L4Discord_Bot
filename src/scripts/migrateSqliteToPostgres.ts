function sqliteTables(db: Database.Database): string[] {
  const rows = db
    .prepare(
      `
      SELECT name
      FROM sqlite_master
      WHERE type = 'table'
        AND name NOT LIKE 'sqlite_%'
        AND name NOT LIKE '%_fts'
        AND name NOT LIKE '%_fts_%'
      ORDER BY name
    `,
    )
    .all() as { name: string }[];
  return rows.map((row) => row.name);
}

function isPacchiBooleanColumn(table: string, column: string): boolean {
  return pacchiBooleanColumns.has(`${table}.${column}`);
}

function isBooleanColumn(table: string, column: string): boolean {
  return isPacchiBooleanColumn(table, column) || youtubeWatcherBooleanColumns.has(`${table}.${column}`);
}

function pgType(table: string, column: SqliteColumn): string {
  const t = column.type.toUpperCase();
  if (snowflakeColumns.has(column.name)) return "text";
  if (isBooleanColumn(table, column.name)) return "boolean";
  if (t.includes("INT")) return "bigint";
  if (t.includes("REAL") || t.includes("FLOA") || t.includes("DOUB")) return "double precision";
  if (t.includes("BLOB")) return "bytea";
  return "text";
}

function columnSql(table: string, column: SqliteColumn, columns: SqliteColumn[]): string {
  const singlePk = columns.filter((c) => Number(c.pk) > 0).length === 1 && Number(column.pk) > 0;
  const generated = singlePk && column.name === "id" && pgType(table, column) === "bigint";
  const parts = [quotePgIdent(column.name), generated ? "bigint generated by default as identity" : pgType(table, column)];
  if (column.notnull || column.pk > 0) parts.push("not null");
  return parts.join(" ");
}

async function ensureTable(pool: Awaited<ReturnType<typeof createPgPool>>, schema: string, table: string, columns: SqliteColumn[]): Promise<void> {
  const pk = columns
    .filter((column) => Number(column.pk) > 0)
    .sort((a, b) => Number(a.pk) - Number(b.pk))
    .map((column) => quotePgIdent(column.name));
  const defs = columns.map((column) => columnSql(table, column, columns));
  if (pk.length > 0) defs.push(`primary key (${pk.join(", ")})`);
  await pool.query(
    `create table if not exists ${quotePgIdent(schema)}.${quotePgIdent(table)} (${defs.join(", ")})`,
  );
}

async function ensureSqliteIndexes(
  pool: Awaited<ReturnType<typeof createPgPool>>,
  sqlite: Database.Database,
  schema: string,
  table: string,
): Promise<void> {
  const indexes = sqlite.prepare(`PRAGMA index_list(${quoteSqliteIdent(table)})`).all() as SqliteIndex[];
  for (const index of indexes) {
    if (index.origin === "pk") continue;
    const cols = sqlite.prepare(`PRAGMA index_info(${quoteSqliteIdent(index.name)})`).all() as SqliteIndexColumn[];
    const names = cols
      .sort((a, b) => Number(a.seqno) - Number(b.seqno))
      .map((col) => col.name)
      .filter(Boolean);
    if (names.length === 0) continue;
    const indexName = `${schema}_${table}_${index.name}`.replace(/[^a-zA-Z0-9_]/g, "_").slice(0, 60);
    const partialWhere = index.partial ? sqliteIndexWhereClause(sqlite, index.name) : null;
    if (index.partial && !partialWhere) {
      console.warn(`[skip] ${schema}.${table}.${index.name}: partial index WHERE clause could not be converted`);
      continue;
    }
    await pool.query(
      `create ${index.unique ? "unique " : ""}index if not exists ${quotePgIdent(indexName)} on ${quotePgIdent(schema)}.${quotePgIdent(table)} (${names.map(quotePgIdent).join(", ")})${partialWhere ? ` where ${partialWhere}` : ""}`,
    );
  }
}

function quoteSqliteIdent(name: string): string {
  return `"${String(name).replace(/"/g, '""')}"`;
}

function sqliteIndexWhereClause(sqlite: Database.Database, indexName: string): string | null {
  const row = sqlite
    .prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?")
    .get(indexName) as SqliteSchemaRow | undefined;
  const sql = row?.sql ?? "";
  const match = /\bWHERE\b([\s\S]+)$/i.exec(sql);
  if (!match) return null;
  return match[1]!
    .trim()
    .replace(/;+\s*$/, "")
    .replace(/"([^"]+)"/g, (_m, ident: string) => quotePgIdent(ident));
}

function normalizeValue(table: string, column: SqliteColumn, value: unknown): unknown {
  if (value === undefined) return null;
  if (value === null) return null;
  if (snowflakeColumns.has(column.name)) return String(value);
  if (isBooleanColumn(table, column.name)) {
    if (typeof value === "bigint") return value !== 0n;
    if (typeof value === "number") return value !== 0;
    if (typeof value === "string") return value !== "0";
  }
  if (typeof value === "bigint") return value.toString();
  if (Buffer.isBuffer(value)) return value;
  return value;
}

async function copyTable(
  pool: Awaited<ReturnType<typeof createPgPool>>,
  sqlite: Database.Database,
  schema: string,
  table: string,
): Promise<number> {
  const columns = sqlite.prepare(`PRAGMA table_info(${quoteSqliteIdent(table)})`).all() as SqliteColumn[];
  if (columns.length === 0) return 0;
  await ensureTable(pool, schema, table, columns);
  await ensureSqliteIndexes(pool, sqlite, schema, table);
  await pool.query(`truncate table ${quotePgIdent(schema)}.${quotePgIdent(table)} restart identity cascade`);

  const rows = sqlite.prepare(`SELECT * FROM ${quoteSqliteIdent(table)}`).all() as Record<string, unknown>[];
  if (rows.length === 0) return 0;

  const colNames = columns.map((column) => column.name);
  const colSql = colNames.map(quotePgIdent).join(", ");
  const chunkSize = 500;
  for (let offset = 0; offset < rows.length; offset += chunkSize) {
    const chunk = rows.slice(offset, offset + chunkSize);
    const values: unknown[] = [];
    const tuples = chunk.map((row, rowIndex) => {
      const params = columns.map((column, colIndex) => {
        values.push(normalizeValue(table, column, row[column.name]));
        return `$${rowIndex * columns.length + colIndex + 1}`;
      });
      return `(${params.join(", ")})`;
    });
    await pool.query(
      `insert into ${quotePgIdent(schema)}.${quotePgIdent(table)} (${colSql}) values ${tuples.join(", ")}`,
      values,
    );
  }

  const idColumn = columns.find((column) => column.name === "id" && pgType(table, column) === "bigint");
  if (idColumn) {
    await pool.query(
      `
      select setval(
        pg_get_serial_sequence($1, 'id'),
        greatest(coalesce((select max(id) from ${quotePgIdent(schema)}.${quotePgIdent(table)}), 0), 1),
        coalesce((select max(id) from ${quotePgIdent(schema)}.${quotePgIdent(table)}), 0) > 0
      )
      `,
      [`${schema}.${table}`],
    ).catch(() => undefined);
  }

  return rows.length;
}

async function ensureCanonicalSchemas(config: ReturnType<typeof loadConfig>): Promise<void> {
  if (!config.DATABASE_URL) throw new Error("DATABASE_URL is required.");
  const mainPool = await createPgPool(config.DATABASE_URL, config.POSTGRES_MAIN_SCHEMA);
  try {
    await applyPostgresMigrations(mainPool, [
      { version: 1, name: "main_core_initial", apply: ensurePostgresMainSchema },
      { version: 2, name: "game_deals_initial", apply: (pool) => ensurePostgresGameDealSchema(pool, config.POSTGRES_MAIN_SCHEMA) },
      { version: 3, name: "ai_provider_initial", apply: (pool) => ensurePostgresAiProviderSchema(pool, config.POSTGRES_MAIN_SCHEMA) },
      { version: 4, name: "senryu_initial", apply: ensurePostgresSenryuSchema },
      { version: 5, name: "lol_watcher_initial", apply: ensurePostgresLolWatcherSchema },
      { version: 6, name: "pacchi_initial", apply: ensurePostgresPacchiSchema },
      { version: 7, name: "polls_state_revision", apply: async (pool) => { await pool.query("ALTER TABLE polls ADD COLUMN IF NOT EXISTS state_revision bigint NOT NULL DEFAULT 0"); } },
      { version: 8, name: "guild_settings_revision", apply: async (pool) => { await pool.query("ALTER TABLE guild_settings ADD COLUMN IF NOT EXISTS revision integer NOT NULL DEFAULT 0"); } },
      { version: 9, name: "vx_twitter_preview_states", apply: async (pool) => { await pool.query(`
        CREATE TABLE IF NOT EXISTS vx_twitter_preview_states (
          message_id text PRIMARY KEY, guild_id text NOT NULL, channel_id text NOT NULL, tweet_url text NOT NULL,
          tweet jsonb NOT NULL, translations jsonb NOT NULL, expires_at timestamptz NOT NULL,
          created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS idx_vx_twitter_preview_states_expires ON vx_twitter_preview_states (expires_at);
      `); } },
      { version: 10, name: "youtube_watcher_initial", apply: ensurePostgresYouTubeWatcherSchema },
      { version: 11, name: "pacchi_boolean_columns", apply: migratePostgresPacchiBooleanColumns },
      { version: 12, name: "drop_steam_app_list_tables", apply: (pool) => dropPostgresSteamAppListTables(pool, config.POSTGRES_MAIN_SCHEMA) },
      { version: 13, name: "youtube_watcher_durable_media", apply: migratePostgresYouTubeWatcherDurableMedia },
      { version: 14, name: "youtube_video_cache_references", apply: migratePostgresYouTubeVideoCacheReferences },
      { version: 15, name: "preview_translation_states", apply: migratePostgresPreviewTranslationStates },
    ]);
  } finally {
    await mainPool.end();
  }

  const tasks: Array<[string, PostgresMigration[]]> = [
    [config.POSTGRES_TICKET_SCHEMA, [{ version: 1, name: "ticket_initial", apply: ensurePostgresTicketDatabaseSchema }]],
    [config.POSTGRES_MESSAGE_LOG_SCHEMA, [{ version: 1, name: "message_logs_initial", apply: ensurePostgresMessageLogsSchema }]],
    [config.POSTGRES_MESSAGE_ATTACHMENT_SCHEMA, [{ version: 1, name: "message_attachments_initial", apply: prepareMessageAttachmentStorePostgres }]],
    [config.POSTGRES_VC_TIME_SCHEMA, [
      { version: 1, name: "vc_time_sessions_initial", apply: ensurePostgresVcTimeSchema },
      { version: 2, name: "vc_temp_initial", apply: ensurePostgresVcTempSchema },
    ]],
    [config.POSTGRES_AI_HISTORY_SCHEMA, [{ version: 1, name: "ai_history_initial", apply: ensurePostgresAiHistorySchema }]],
    [config.POSTGRES_AUTOMOD_SCHEMA, [{ version: 1, name: "automod_initial", apply: ensurePostgresAutomoderationSchema }]],
    [config.POSTGRES_REMINDER_SCHEMA, [{ version: 1, name: "reminder_initial", apply: ensurePostgresReminderSchema }]],
  ];

  for (const [schema, migrations] of tasks) {
    const pool = await createPgPool(config.DATABASE_URL, schema);
    try {
      await applyPostgresMigrations(pool, migrations);
    } finally {
      await pool.end();
    }
  }
}

async function migrateSource(pool: Awaited<ReturnType<typeof createPgPool>>, source: SourceDb): Promise<void> {
  if (!existsSync(source.path)) {
    console.warn(`[skip] ${source.label}: SQLite file not found: ${source.path}`);
    return;
  }
  await pool.query(`create schema if not exists ${quotePgIdent(source.schema)}`);
  const sqlite = new Database(source.path, { readonly: true, fileMustExist: true });
  sqlite.defaultSafeIntegers(true);
  try {
    const tables = sqliteTables(sqlite).sort((a, b) => {
      if (a === "youtube_watch_subscriptions") return -1;
      if (b === "youtube_watch_subscriptions") return 1;
      return a.localeCompare(b);
    });
    for (const table of tables) {
      if (source.label === "main" && retiredMainTables.has(table)) {
        console.log(`[skip] ${source.label}.${table}: retired Steam AppList table`);
        continue;
      }
      const count = await copyTable(pool, sqlite, source.schema, table);
      console.log(`[copy] ${source.label}.${table} -> ${source.schema}.${table}: ${count}`);
    }
  } finally {
    sqlite.close();
  }
}

async function main(): Promise<void> {
  const config = loadConfig();
  if (!config.DATABASE_URL) throw new Error("DATABASE_URL is required.");
  const pool = await createPgPool(config.DATABASE_URL);
  const sources: SourceDb[] = [
    { label: "main", path: config.DATABASE_PATH, schema: config.POSTGRES_MAIN_SCHEMA },
    { label: "ticket", path: config.TICKET_DATABASE_PATH, schema: config.POSTGRES_TICKET_SCHEMA },
    { label: "message_log", path: config.MESSAGE_LOG_DB_PATH, schema: config.POSTGRES_MESSAGE_LOG_SCHEMA },
    {
      label: "message_attachment",
      path: config.MESSAGE_ATTACHMENT_STORE_DB_PATH,
      schema: config.POSTGRES_MESSAGE_ATTACHMENT_SCHEMA,
    },
    { label: "vc_time", path: config.VC_TIME_DATABASE_PATH, schema: config.POSTGRES_VC_TIME_SCHEMA },
    { label: "ai_history", path: config.AI_HISTORY_DATABASE_PATH, schema: config.POSTGRES_AI_HISTORY_SCHEMA },
    { label: "automod", path: config.AUTOMODERATION_DATABASE_PATH, schema: config.POSTGRES_AUTOMOD_SCHEMA },
    { label: "reminder", path: config.REMINDER_DATABASE_PATH, schema: config.POSTGRES_REMINDER_SCHEMA },
  ];

  try {
    // Generic SQLite introspection does not preserve DEFAULT/CHECK/FK clauses.
    // Create canonical runtime tables first so copied rows land in runtime-compatible schemas.
    await ensureCanonicalSchemas(config);
    for (const source of sources) {
      await migrateSource(pool, source);
    }
    const mainPool = await createPgPool(config.DATABASE_URL, config.POSTGRES_MAIN_SCHEMA);
    try {
      await migratePostgresYouTubeVideoCacheReferences(mainPool);
    } finally {
      await mainPool.end();
    }
  } finally {
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

