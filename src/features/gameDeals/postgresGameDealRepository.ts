function pgStringLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function legacyBooleanColumnMigrationSql(schema: string, schemaName: string, table: string, column: "active" | "enabled"): string {
  const schemaLiteral = pgStringLiteral(schemaName);
  const tableLiteral = pgStringLiteral(table);
  return `
    DO $$
    BEGIN
      IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = ${schemaLiteral}
          AND table_name = ${tableLiteral}
          AND column_name = '${column}'
          AND data_type <> 'boolean'
      ) THEN
        ALTER TABLE ${schema}.${table} ALTER COLUMN ${column} DROP DEFAULT;
        ALTER TABLE ${schema}.${table}
          ALTER COLUMN ${column} TYPE boolean
          USING CASE
            WHEN ${column} IS NULL THEN false
            WHEN lower(${column}::text) IN ('1', 'true', 't', 'yes', 'on') THEN true
            ELSE false
          END;
      END IF;
      UPDATE ${schema}.${table} SET ${column} = false WHERE ${column} IS NULL;
      ALTER TABLE ${schema}.${table} ALTER COLUMN ${column} SET DEFAULT true;
      ALTER TABLE ${schema}.${table} ALTER COLUMN ${column} SET NOT NULL;
    END $$;
  `;
}

export async function ensurePostgresGameDealSchema(pool: PgQueryable, schemaName: string): Promise<void> {
  const schema = quotePgIdent(schemaName);

  await pool.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
  await pool.query(`
    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_notify_channels (
      guild_id text PRIMARY KEY,
      channel_id text NOT NULL,
      enabled boolean NOT NULL DEFAULT true,
      created_at text NOT NULL,
      updated_at text NOT NULL
    );

    CREATE INDEX IF NOT EXISTS game_deal_notify_channels_enabled_idx
      ON ${schema}.game_deal_notify_channels (enabled);

    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_detected_items (
      id bigint generated by default as identity primary key,
      platform text NOT NULL,
      title text NOT NULL,
      dedupe_key text NOT NULL UNIQUE,
      first_detected_at text NOT NULL,
      last_seen_at text NOT NULL,
      notified_at text,
      active boolean NOT NULL DEFAULT true
    );

    CREATE INDEX IF NOT EXISTS game_deal_detected_items_active_idx
      ON ${schema}.game_deal_detected_items (active, last_seen_at DESC);

    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_watcher_status (
      id bigint PRIMARY KEY,
      last_scan_at text,
      last_success_at text,
      last_error text,
      last_detected_count integer NOT NULL DEFAULT 0,
      last_steam_search_status text,
      last_steam_search_error text,
      steam_search_cooldown_until text,
      CONSTRAINT game_deal_watcher_status_singleton CHECK (id = 1)
    );

    INSERT INTO ${schema}.game_deal_watcher_status (id, last_detected_count)
    VALUES (1, 0)
    ON CONFLICT (id) DO NOTHING;

    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_subscriptions (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      user_id text NOT NULL,
      platform text NOT NULL,
      target_id text NOT NULL,
      url text NOT NULL,
      title text,
      last_state_key text,
      last_notified_at text,
      active boolean NOT NULL DEFAULT true,
      created_at text NOT NULL,
      updated_at text NOT NULL
    );

    CREATE INDEX IF NOT EXISTS game_deal_subscriptions_active_guild_idx
      ON ${schema}.game_deal_subscriptions (active, guild_id);

    CREATE INDEX IF NOT EXISTS game_deal_subscriptions_active_guild_user_updated_idx
      ON ${schema}.game_deal_subscriptions (active, guild_id, user_id, updated_at DESC);

    CREATE INDEX IF NOT EXISTS game_deal_subscriptions_target_lookup_idx
      ON ${schema}.game_deal_subscriptions (guild_id, user_id, platform, target_id, active);

    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_subscription_notifications (
      id text PRIMARY KEY,
      subscription_id text NOT NULL,
      user_id text NOT NULL,
      message_id text,
      action_pressed text,
      pressed_at text,
      guild_id text,
      target_platform text,
      target_id text,
      created_at text NOT NULL
    );

    CREATE INDEX IF NOT EXISTS game_deal_subscription_notifications_subscription_idx
      ON ${schema}.game_deal_subscription_notifications (subscription_id);

    CREATE TABLE IF NOT EXISTS ${schema}.deal_watch_items (
      id bigint generated by default as identity primary key,
      guild_id text NOT NULL,
      channel_id text,
      steam_app_id text NOT NULL,
      title text,
      last_deal_id text,
      last_sale_price double precision,
      last_normal_price double precision,
      last_savings double precision,
      last_change integer,
      last_checked_at text,
      last_notified_at text,
      created_at text NOT NULL,
      updated_at text NOT NULL,
      enabled boolean NOT NULL DEFAULT true,
      UNIQUE (guild_id, steam_app_id)
    );

    CREATE INDEX IF NOT EXISTS deal_watch_items_enabled_guild_updated_idx
      ON ${schema}.deal_watch_items (enabled, guild_id, updated_at DESC);

    CREATE INDEX IF NOT EXISTS deal_watch_items_enabled_idx
      ON ${schema}.deal_watch_items (enabled);

    CREATE TABLE IF NOT EXISTS ${schema}.deal_detected_items (
      id bigint generated by default as identity primary key,
      source text NOT NULL,
      detected_type text NOT NULL,
      deal_id text,
      steam_app_id text,
      title text NOT NULL,
      sale_price double precision,
      normal_price double precision,
      savings double precision,
      last_change integer,
      cheapshark_url text,
      steam_url text,
      image_url text,
      dedupe_key text NOT NULL UNIQUE,
      first_detected_at text NOT NULL,
      last_seen_at text NOT NULL,
      notified_at text,
      active boolean NOT NULL DEFAULT true
    );

    CREATE INDEX IF NOT EXISTS deal_detected_items_active_idx
      ON ${schema}.deal_detected_items (active, last_seen_at DESC);

    CREATE TABLE IF NOT EXISTS ${schema}.game_deal_status (
      id bigint PRIMARY KEY,
      last_scan_at text,
      last_success_at text,
      last_error text,
      last_detected_count integer NOT NULL DEFAULT 0,
      cheapshark_cooldown_until text,
      CONSTRAINT game_deal_status_singleton CHECK (id = 1)
    );

    INSERT INTO ${schema}.game_deal_status (id, last_detected_count)
    VALUES (1, 0)
    ON CONFLICT (id) DO NOTHING;

    CREATE TABLE IF NOT EXISTS ${schema}.steam_paid_price_history (
      appid text PRIMARY KEY,
      title text,
      normal_price_cents integer,
      normal_price_display text,
      source text NOT NULL,
      first_paid_seen_at text NOT NULL,
      last_paid_seen_at text NOT NULL,
      updated_at text NOT NULL
    );

    CREATE TABLE IF NOT EXISTS ${schema}.steam_free_events (
      id bigint generated by default as identity primary key,
      appid text NOT NULL,
      title text NOT NULL,
      state_key text NOT NULL UNIQUE,
      price_change_number integer,
      last_modified integer,
      normal_price_cents integer,
      current_price_cents integer NOT NULL DEFAULT 0,
      discount_percent integer,
      evidence_json text NOT NULL,
      steam_url text NOT NULL,
      image_url text,
      first_detected_at text NOT NULL,
      last_seen_at text NOT NULL,
      notified_at text,
      active boolean NOT NULL DEFAULT true
    );

    CREATE INDEX IF NOT EXISTS steam_free_events_active_last_seen_idx
      ON ${schema}.steam_free_events (active, last_seen_at DESC);

    CREATE INDEX IF NOT EXISTS steam_free_events_appid_idx
      ON ${schema}.steam_free_events (appid);

  `);
  await pool.query(
    [
      legacyBooleanColumnMigrationSql(schema, schemaName, "game_deal_notify_channels", "enabled"),
      legacyBooleanColumnMigrationSql(schema, schemaName, "game_deal_detected_items", "active"),
      legacyBooleanColumnMigrationSql(schema, schemaName, "game_deal_subscriptions", "active"),
      legacyBooleanColumnMigrationSql(schema, schemaName, "deal_watch_items", "enabled"),
      legacyBooleanColumnMigrationSql(schema, schemaName, "deal_detected_items", "active"),
      legacyBooleanColumnMigrationSql(schema, schemaName, "steam_free_events", "active"),
    ].join("\n"),
  );
}

