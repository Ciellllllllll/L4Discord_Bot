import type { PgQueryable } from "../../core/db/postgres.js";

export async function ensurePostgresVcTimeSchema(pool: PgQueryable): Promise<void> {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS sessions (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      guild_id text NOT NULL,
      user_id text NOT NULL,
      channel_id text NOT NULL,
      started_at text NOT NULL,
      ended_at text,
      duration_sec bigint
    );
    DROP INDEX IF EXISTS idx_sessions_guild_user_open;
    CREATE INDEX IF NOT EXISTS idx_sessions_open ON sessions(guild_id, user_id, ended_at);
    CREATE INDEX IF NOT EXISTS idx_sessions_time ON sessions(started_at);
    CREATE INDEX IF NOT EXISTS idx_sessions_channel ON sessions(channel_id);
  `);
}
