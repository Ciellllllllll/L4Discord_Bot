import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { dirname, isAbsolute } from "node:path";
import { quotePgIdent } from "./postgres.js";

type RunResult = {
  changes: number;
  lastInsertRowid: number | bigint;
};

type BindValue = string | number | bigint | boolean | null | undefined | Buffer | Date;
type BindParams = BindValue[] | Record<string, BindValue>;

const snowflakeColumns = new Set([
  "guild_id",
  "channel_id",
  "message_id",
  "user_id",
  "author_id",
  "opener_id",
  "assignee_id",
  "executor_id",
  "target_id",
  "thread_id",
  "source_message_id",
  "confirm_message_id",
  "author_staff_id",
  "approver_staff_id",
  "reviewer_id",
  "review_message_id",
  "hold_thread_id",
]);

function pgLiteral(value: BindValue): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return "NULL";
    return String(value);
  }
  if (typeof value === "bigint") return pgLiteral(value.toString());
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (value instanceof Date) return pgLiteral(value.toISOString());
  if (Buffer.isBuffer(value)) return `decode('${value.toString("hex")}', 'hex')`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function normalizeParams(params: unknown[]): BindParams {
  if (params.length === 1 && params[0] && typeof params[0] === "object" && !Array.isArray(params[0]) && !Buffer.isBuffer(params[0])) {
    return params[0] as Record<string, BindValue>;
  }
  return params as BindValue[];
}

function bindSql(sql: string, params: BindParams): string {
  if (Array.isArray(params)) {
    let index = 0;
    return sql.replace(/\?/g, () => pgLiteral(params[index++]));
  }
  return sql.replace(/[@:$]([A-Za-z_][A-Za-z0-9_]*)/g, (match, name: string) => {
    if (!(name in params)) return match;
    return pgLiteral(params[name]);
  });
}

function stripTrailingSemicolon(sql: string): string {
  return sql.trim().replace(/;+\s*$/, "");
}

function pragmaTableInfoName(sql: string): string | null {
  const match = /^\s*PRAGMA\s+table_info\s*\(\s*["'`]?([A-Za-z_][A-Za-z0-9_]*)["'`]?\s*\)\s*;?\s*$/i.exec(sql);
  return match?.[1] ?? null;
}

function quoteCamelCaseAliases(sql: string): string {
  return sql.replace(/\bAS\s+([A-Za-z_][A-Za-z0-9_]*)\b/g, (match, alias: string) => {
    if (!/[a-z][A-Z]/.test(alias)) return match;
    return `AS ${quotePgIdent(alias)}`;
  });
}

function translateSql(sql: string): string {
  let next = stripTrailingSemicolon(sql);
  next = quoteCamelCaseAliases(next);
  const insertOrIgnore = /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(next);
  next = next.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, "INSERT INTO");
  if (insertOrIgnore && /^\s*INSERT\s+INTO\b/i.test(next) && !/\bON\s+CONFLICT\b/i.test(next)) {
    next += " ON CONFLICT DO NOTHING";
  }
  next = next.replace(
    /MAX\(\s*steam_paid_price_history\.normal_price_cents\s*,\s*excluded\.normal_price_cents\s*\)/gi,
    "GREATEST(steam_paid_price_history.normal_price_cents, excluded.normal_price_cents)",
  );
  next = next.replace(
    /min\(\s*pacchi_sentence_patterns\.safe_level\s*,\s*excluded\.safe_level\s*\)/gi,
    "LEAST(pacchi_sentence_patterns.safe_level, excluded.safe_level)",
  );
  return next;
}

function stripSqliteOnlyDdl(sql: string): string {
  return sql
    .replace(/\bCREATE\s+TRIGGER\b[\s\S]*?\bEND\s*;/gi, "")
    .replace(/\bCREATE\s+VIRTUAL\s+TABLE\b[\s\S]*?;\s*/gi, "")
    .replace(/\bDROP\s+TRIGGER\b[\s\S]*?;\s*/gi, "");
}

function splitStatements(sql: string): string[] {
  return stripSqliteOnlyDdl(sql)
    .split(";")
    .map((statement) => statement.trim())
    .filter(Boolean);
}

function translateSqliteTypeFragments(sql: string): string {
  let next = sql;
  for (const column of snowflakeColumns) {
    next = next.replace(new RegExp(`\\b(${column})\\s+INTEGER\\b`, "gi"), "$1 text");
    next = next.replace(new RegExp(`\\b("${column}")\\s+INTEGER\\b`, "gi"), "$1 text");
  }
  return next
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, "bigint generated by default as identity primary key")
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\b/gi, "bigint primary key")
    .replace(/\bAUTOINCREMENT\b/gi, "")
    .replace(/\bINTEGER\b/gi, "bigint")
    .replace(/\bREAL\b/gi, "double precision")
    .replace(/\bBLOB\b/gi, "bytea")
    .replace(/\bTEXT\b/gi, "text")
    .replace(/DEFAULT\s+\(\s*datetime\(\s*'now'\s*\)\s*\)/gi, "DEFAULT (CURRENT_TIMESTAMP::text)");
}

function splitTopLevelComma(source: string): string[] {
  const out: string[] = [];
  let start = 0;
  let depth = 0;
  let quote: string | null = null;
  for (let i = 0; i < source.length; i += 1) {
    const ch = source[i]!;
    if (quote) {
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === "\"") {
      quote = ch;
      continue;
    }
    if (ch === "(") depth += 1;
    else if (ch === ")") depth = Math.max(0, depth - 1);
    else if (ch === "," && depth === 0) {
      out.push(source.slice(start, i).trim());
      start = i + 1;
    }
  }
  out.push(source.slice(start).trim());
  return out.filter(Boolean);
}

function createTableMissingColumnSql(sql: string): string[] {
  const match = /^\s*CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+("?[\w]+"?)\s*\(([\s\S]+)\)\s*$/i.exec(sql);
  if (!match) return [];
  const table = match[1]!;
  return splitTopLevelComma(match[2]!)
    .filter((def) => !/^(PRIMARY|UNIQUE|CHECK|FOREIGN|CONSTRAINT)\b/i.test(def))
    .map((def) => {
      const translated = translateSqliteTypeFragments(def)
        .replace(/\s+PRIMARY\s+KEY\b/gi, "")
        .replace(/\s+generated\s+by\s+default\s+as\s+identity\b/gi, "");
      return `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${translated}`;
    });
}

function translateDdl(sql: string): string[] {
  const trimmed = stripTrailingSemicolon(sql);
  if (!trimmed) return [];
  if (/^\s*CREATE\s+VIRTUAL\s+TABLE\b/i.test(trimmed)) return [];
  if (/^\s*(CREATE|DROP)\s+TRIGGER\b/i.test(trimmed)) return [];
  if (/^\s*CREATE\s+TABLE\b/i.test(trimmed)) {
    const create = translateSqliteTypeFragments(trimmed);
    return [create, ...createTableMissingColumnSql(trimmed)];
  }
  if (/^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\b/i.test(trimmed)) {
    return [translateSqliteTypeFragments(trimmed)];
  }
  const alter = /^\s*ALTER\s+TABLE\s+("?[\w]+"?)\s+ADD\s+COLUMN\s+(.+)$/i.exec(trimmed);
  if (alter) {
    return [`ALTER TABLE ${alter[1]} ADD COLUMN IF NOT EXISTS ${translateSqliteTypeFragments(alter[2]!)}`];
  }
  return [translateSql(trimmed)];
}

function resolvePsqlBin(): string {
  const configured = process.env.PSQL_BIN?.trim();
  if (configured) {
    if (!isAbsolute(configured)) throw new Error("PSQL_BIN must be an absolute path.");
    return configured;
  }
  if (process.platform !== "win32" && existsSync("/usr/bin/psql")) return "/usr/bin/psql";
  return "psql";
}

function normalizeRow(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(normalizeRow);
  if (!value || typeof value !== "object") return value;
  const out: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value)) {
    out[key] = normalizeRow(entry);
  }
  return out;
}

function parseJsonLines(source: string): unknown[] {
  return source
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => JSON.parse(line));
}

export class SyncPostgresStatement {
  constructor(
    private readonly db: SyncPostgresCompatDatabase,
    private readonly sourceSql: string,
  ) {}

  get<T = unknown>(...params: unknown[]): T | undefined {
    return this.all<T>(...params)[0];
  }

  all<T = unknown>(...params: unknown[]): T[] {
    const sql = translateSql(bindSql(this.sourceSql, normalizeParams(params)));
    const table = pragmaTableInfoName(sql);
    if (table) {
      return this.db.tableInfo(table) as T[];
    }
    const out = this.db.queryJsonLines(sql);
    return out.map((row) => normalizeRow(row) as T);
  }

  run(...params: unknown[]): RunResult {
    const sql = translateSql(bindSql(this.sourceSql, normalizeParams(params)));
    const changes = this.db.executeMutation(sql);
    return { changes, lastInsertRowid: 0 };
  }
}

export class SyncPostgresCompatDatabase {
  private transactionStatements: string[] | null = null;

  constructor(
    private readonly connectionString: string,
    private readonly schema: string,
  ) {}

  prepare(sql: string): SyncPostgresStatement {
    return new SyncPostgresStatement(this, sql);
  }

  exec(sql: string): void {
    for (const statement of splitStatements(sql)) {
      for (const translated of translateDdl(statement)) {
        this.psql(translated);
      }
    }
  }

  pragma(_source: string): unknown {
    return [];
  }

  defaultSafeIntegers(_enabled?: boolean): this {
    return this;
  }

  close(): void {
    return;
  }

  transaction<T extends (...args: any[]) => any>(fn: T): T {
    return ((...args: Parameters<T>) => {
      if (this.transactionStatements) {
        return fn(...args);
      }
      this.transactionStatements = [];
      try {
        const result = fn(...args);
        const statements = this.transactionStatements;
        if (statements.length > 0) {
          this.psql(`BEGIN;\n${statements.join(";\n")};\nCOMMIT;`);
        }
        return result;
      } finally {
        this.transactionStatements = null;
      }
    }) as T;
  }

  queryJsonLines(sql: string): unknown[] {
    const wrapped = `SELECT row_to_json(__q) FROM (${sql}) AS __q`;
    return parseJsonLines(this.psql(wrapped));
  }

  tableInfo(table: string): Array<{ cid: number; name: string; type: string; notnull: number; dflt_value: string | null; pk: number }> {
    return this.queryJsonLines(
      `
        SELECT
          (ordinal_position - 1)::int AS cid,
          column_name AS name,
          data_type AS type,
          CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
          column_default AS dflt_value,
          0 AS pk
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = ${pgLiteral(table)}
        ORDER BY ordinal_position
      `,
    ) as Array<{ cid: number; name: string; type: string; notnull: number; dflt_value: string | null; pk: number }>;
  }

  executeMutation(sql: string): number {
    const trimmed = sql.trim();
    if (this.transactionStatements) {
      this.transactionStatements.push(trimmed);
      return 1;
    }
    if (/^(UPDATE|DELETE)\b/i.test(trimmed) && !/\bRETURNING\b/i.test(trimmed)) {
      const wrapped = `WITH __dml AS (${trimmed} RETURNING 1) SELECT row_to_json(__q) FROM (SELECT count(*)::int AS changes FROM __dml) AS __q`;
      const rows = parseJsonLines(this.psql(wrapped)) as Array<{ changes?: number }>;
      return Number(rows[0]?.changes ?? 0);
    }
    if (/^INSERT\b/i.test(trimmed) && !/\bRETURNING\b/i.test(trimmed)) {
      const wrapped = `WITH __dml AS (${trimmed} RETURNING 1) SELECT row_to_json(__q) FROM (SELECT count(*)::int AS changes FROM __dml) AS __q`;
      const rows = parseJsonLines(this.psql(wrapped)) as Array<{ changes?: number }>;
      return Number(rows[0]?.changes ?? 0);
    }
    const rows = this.queryJsonLines(trimmed) as unknown[];
    return rows.length;
  }

  private psql(sql: string): string {
    const searchPath = `${quotePgIdent(this.schema)},public`;
    const fullSql = `SET search_path TO ${searchPath};\n${sql}`;
    const url = new URL(this.connectionString);
    const psqlBin = resolvePsqlBin();
    const psqlDir = isAbsolute(psqlBin) ? dirname(psqlBin) : process.env.PATH;
    const sslMode = url.searchParams.get("sslmode");
    return execFileSync(
      psqlBin,
      [
        "-h",
        url.hostname,
        "-p",
        url.port || "5432",
        "-U",
        decodeURIComponent(url.username),
        "-d",
        decodeURIComponent(url.pathname.replace(/^\//, "")),
        "-X",
        "-q",
        "-v",
        "ON_ERROR_STOP=1",
        "-t",
        "-A",
        "-c",
        fullSql,
      ],
      {
        encoding: "utf8",
        env: {
          PATH: psqlDir,
          SYSTEMROOT: process.env.SYSTEMROOT,
          SystemRoot: process.env.SystemRoot,
          PGPASSWORD: decodeURIComponent(url.password),
          ...(sslMode ? { PGSSLMODE: sslMode } : {}),
        },
        maxBuffer: 32 * 1024 * 1024,
        stdio: ["ignore", "pipe", "pipe"],
        timeout: 5_000,
      },
    ).trim();
  }
}

export function createSyncPostgresCompatDatabase(connectionString: string, schema: string): SyncPostgresCompatDatabase {
  return new SyncPostgresCompatDatabase(connectionString, schema);
}
