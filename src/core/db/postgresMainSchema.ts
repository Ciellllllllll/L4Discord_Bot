import type { PgQueryable } from "./postgres.js";

export async function ensurePostgresMainSchema(pool: PgQueryable): Promise<void> {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS guild_settings (
      guild_id text PRIMARY KEY,
      data jsonb NOT NULL DEFAULT '{}'::jsonb,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      revision integer NOT NULL DEFAULT 0
    );

    CREATE TABLE IF NOT EXISTS interaction_sessions (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      domain text NOT NULL,
      action text NOT NULL,
      payload jsonb NOT NULL DEFAULT '{}'::jsonb,
      executor_user_id text,
      expires_at timestamptz NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_interaction_sessions_expires ON interaction_sessions (expires_at);

    CREATE TABLE IF NOT EXISTS detecter_incidents (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      audit_entry_id text NOT NULL UNIQUE,
      executor_id text NOT NULL,
      target_id text NOT NULL,
      action_type text NOT NULL,
      reason text,
      appeal_ticket_id text,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS audit_log_cursors (
      guild_id text PRIMARY KEY,
      last_snowflake text NOT NULL
    );

    CREATE TABLE IF NOT EXISTS werewolf_games (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      host_id text NOT NULL,
      phase text NOT NULL DEFAULT 'lobby',
      state jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS economy_accounts (
      guild_id text NOT NULL,
      user_id text NOT NULL,
      balance bigint NOT NULL DEFAULT 0,
      xp bigint NOT NULL DEFAULT 0,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (guild_id, user_id)
    );

    CREATE TABLE IF NOT EXISTS economy_ledger (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      guild_id text NOT NULL,
      user_id text NOT NULL,
      delta bigint NOT NULL,
      reason text NOT NULL,
      meta jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_economy_ledger_guild_user ON economy_ledger (guild_id, user_id);

    CREATE TABLE IF NOT EXISTS keyword_stats (
      guild_id text NOT NULL,
      user_id text NOT NULL,
      keyword_key text NOT NULL,
      count bigint NOT NULL DEFAULT 0,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (guild_id, user_id, keyword_key)
    );

    CREATE TABLE IF NOT EXISTS reaction_role_messages (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      message_id text NOT NULL,
      config jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (guild_id, channel_id, message_id)
    );

    CREATE TABLE IF NOT EXISTS reaction_role_entries (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      entry_id text NOT NULL,
      channel_id text NOT NULL,
      message_id text,
      title text NOT NULL,
      description text NOT NULL DEFAULT '',
      roles_json text NOT NULL DEFAULT '[]',
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (guild_id, entry_id)
    );
    CREATE INDEX IF NOT EXISTS idx_reaction_role_entries_guild ON reaction_role_entries(guild_id);

    CREATE TABLE IF NOT EXISTS panel_messages (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      panel_kind text NOT NULL,
      channel_id text NOT NULL,
      message_id text NOT NULL,
      data jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (guild_id, panel_kind)
    );

    CREATE TABLE IF NOT EXISTS stamp_usage (
      guild_id text NOT NULL,
      user_id text NOT NULL,
      emoji_id text NOT NULL,
      emoji_name text NOT NULL,
      count bigint NOT NULL DEFAULT 0,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (guild_id, user_id, emoji_id)
    );

    CREATE TABLE IF NOT EXISTS todos (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text,
      author_id text NOT NULL,
      title text NOT NULL,
      body text,
      status text NOT NULL DEFAULT 'open',
      due_at text,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_todos_guild_status ON todos(guild_id, status);

    CREATE TABLE IF NOT EXISTS announcements (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      author_id text NOT NULL,
      title text NOT NULL,
      body text NOT NULL,
      scheduled_at text,
      posted_at text,
      status text NOT NULL DEFAULT 'draft',
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_announcements_guild_status ON announcements(guild_id, status);

    CREATE TABLE IF NOT EXISTS vc_panel_configs (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      category_id text NOT NULL,
      name text NOT NULL,
      data jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (guild_id, category_id)
    );

    CREATE TABLE IF NOT EXISTS polls (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      message_id text,
      kind text NOT NULL,
      status text NOT NULL DEFAULT 'open',
      state jsonb NOT NULL DEFAULT '{}'::jsonb,
      state_revision bigint NOT NULL DEFAULT 0,
      ends_at text,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_polls_guild_status ON polls(guild_id, status);

    CREATE TABLE IF NOT EXISTS ai_r18_user_settings (
      guild_id text NOT NULL,
      user_id text NOT NULL,
      enabled smallint NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
      updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      PRIMARY KEY (guild_id, user_id)
    );

    CREATE TABLE IF NOT EXISTS anonymous_survey_responses (
      id text PRIMARY KEY,
      guild_id text NOT NULL,
      rating integer NOT NULL CHECK (rating >= 1 AND rating <= 5),
      created_at timestamptz NOT NULL
    );

    CREATE TABLE IF NOT EXISTS anonymous_survey_user_state (
      guild_id text NOT NULL,
      user_id text NOT NULL,
      last_action text NOT NULL CHECK (last_action IN ('answer', 'skip')),
      next_prompt_at timestamptz NOT NULL,
      updated_at timestamptz NOT NULL,
      PRIMARY KEY (guild_id, user_id)
    );

    CREATE TABLE IF NOT EXISTS vx_twitter_preview_states (
      message_id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      tweet_url text NOT NULL,
      tweet jsonb NOT NULL,
      translations jsonb NOT NULL,
      expires_at timestamptz NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_vx_twitter_preview_states_expires ON vx_twitter_preview_states (expires_at);

    CREATE TABLE IF NOT EXISTS preview_translation_states (
      message_id text PRIMARY KEY,
      guild_id text NOT NULL,
      channel_id text NOT NULL,
      source_kind text NOT NULL CHECK (source_kind IN ('x', 'youtube', 'steam', 'github')),
      source_url text NOT NULL,
      document jsonb NOT NULL,
      translations jsonb NOT NULL,
      expires_at timestamptz NOT NULL,
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_preview_translation_states_expires ON preview_translation_states (expires_at);

    CREATE TABLE IF NOT EXISTS steam_exchange_rates (
      rate_date date NOT NULL,
      rate numeric(12, 6),
      status text NOT NULL CHECK (status IN ('pending', 'succeeded', 'failed')),
      attempted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      fetched_at timestamptz,
      error_message text,
      PRIMARY KEY (rate_date)
    );
    CREATE INDEX IF NOT EXISTS idx_steam_exchange_rates_latest
      ON steam_exchange_rates (rate_date DESC)
      WHERE status = 'succeeded' AND rate IS NOT NULL;
  `);
}
